/// Derive a short model key from a full model name.
///
/// Examples:
///   - `"meta-llama/Llama-3-70b"` → `"llama-3-70b"`
///   - `"gpt-4o"` → `"gpt-4o"`
///   - `"opus"` → `"opus"`
///   - `""` → `"model"`
fn model_key_from_name(model_name: &str) -> String {
    // Take the part after the last '/' if present, then lowercase
    let base = model_name.rsplit('/').next().unwrap_or(model_name);
    let key = base.to_lowercase().replace(' ', "-").replace(
        |c: char| !c.is_alphanumeric() && c != '-' && c != '_' && c != '.',
        "-",
    );
    // TODO(slop): add test for new `if` branch (no paired test file in this patch)
    if key.is_empty() {
        "model".to_string()
    } else {
        key
    }
}

fn escape_yaml_double_quoted(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "\\r")
        .replace('\t', "\\t")
}

